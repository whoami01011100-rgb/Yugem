CREATE OR REPLACE TRIGGER TRG_YUGEM_USERS_ID
BEFORE INSERT ON YUGEM_USERS
FOR EACH ROW
WHEN (NEW.USER_ID IS NULL)
BEGIN
    SELECT YUGEM_USERS_SEQ.NEXTVAL
    INTO :NEW.USER_ID
    FROM DUAL;
END;
/

