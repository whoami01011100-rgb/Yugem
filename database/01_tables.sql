CREATE TABLE YUGEM_USERS (
    USER_ID NUMBER(10) PRIMARY KEY,
    EMPLOYEE_ID VARCHAR2(30) NOT NULL,
    LOGIN_ID VARCHAR2(50) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(100) NOT NULL,
    ROLE_NAME VARCHAR2(30) DEFAULT 'BDE' NOT NULL,
    CONTACT_NO VARCHAR2(20),
    EMAIL VARCHAR2(150),
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

ALTER TABLE YUGEM_USERS
ADD CONSTRAINT UK_YUGEM_USERS_EMP UNIQUE (EMPLOYEE_ID);

ALTER TABLE YUGEM_USERS
ADD CONSTRAINT UK_YUGEM_USERS_LOGIN UNIQUE (LOGIN_ID);

ALTER TABLE YUGEM_USERS
ADD CONSTRAINT CK_YUGEM_USERS_ACTIVE
CHECK (IS_ACTIVE IN ('Y','N'));


CREATE TABLE YUGEM_CLIENTS (
    CLIENT_ID NUMBER(10) PRIMARY KEY,
    CLIENT_NAME VARCHAR2(150) NOT NULL,
    CONTACT_NO VARCHAR2(20),
    EMAIL VARCHAR2(150),
    COMPANY_NAME VARCHAR2(200),
    COMPANY_TYPE VARCHAR2(100),
    ADDRESS VARCHAR2(500),
    CREATED_BY NUMBER(10),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

ALTER TABLE YUGEM_CLIENTS
ADD CONSTRAINT FK_CLIENT_CREATED_BY
FOREIGN KEY (CREATED_BY)
REFERENCES YUGEM_USERS(USER_ID);


CREATE TABLE YUGEM_BDMS (
    BDM_ID NUMBER(10) PRIMARY KEY,
    BDM_NAME VARCHAR2(100) NOT NULL,
    CONTACT_NO VARCHAR2(20),
    EMAIL VARCHAR2(150),
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE YUGEM_BDMS
ADD CONSTRAINT CK_BDM_ACTIVE
CHECK (IS_ACTIVE IN ('Y','N'));


CREATE TABLE YUGEM_SERVICES (
    SERVICE_ID NUMBER(10) PRIMARY KEY,
    SERVICE_NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE YUGEM_SERVICES
ADD CONSTRAINT UK_SERVICE_NAME
UNIQUE (SERVICE_NAME);

ALTER TABLE YUGEM_SERVICES
ADD CONSTRAINT CK_SERVICE_ACTIVE
CHECK (IS_ACTIVE IN ('Y','N'));


CREATE TABLE YUGEM_SUB_SERVICES (
    SUB_SERVICE_ID NUMBER(10) PRIMARY KEY,
    SERVICE_ID NUMBER(10) NOT NULL,
    SUB_SERVICE_NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE YUGEM_SUB_SERVICES
ADD CONSTRAINT FK_SUBSERVICE_SERVICE
FOREIGN KEY (SERVICE_ID)
REFERENCES YUGEM_SERVICES(SERVICE_ID);

ALTER TABLE YUGEM_SUB_SERVICES
ADD CONSTRAINT CK_SUBSERVICE_ACTIVE
CHECK (IS_ACTIVE IN ('Y','N'));


CREATE TABLE YUGEM_PAYMENTS (
    PAYMENT_ID NUMBER(12) PRIMARY KEY,
    BDE_USER_ID NUMBER(10) NOT NULL,
    BDE_NAME VARCHAR2(100),
    EMPLOYEE_ID VARCHAR2(30),
    PAYMENT_DATE DATE NOT NULL,
    PAYMENT_TIME VARCHAR2(20),
    CLIENT_ID NUMBER(10),
    CLIENT_NAME VARCHAR2(150),
    CLIENT_CONTACT VARCHAR2(20),
    CLIENT_EMAIL VARCHAR2(150),
    COMPANY_NAME VARCHAR2(200),
    COMPANY_TYPE VARCHAR2(100),
    PAYMENT_PERCENTAGE NUMBER(7,2),
    SERVICE_FEE NUMBER(14,2),
    GST_STATUS VARCHAR2(20),
    BASIC_AMOUNT NUMBER(14,2) DEFAULT 0,
    GST_AMOUNT NUMBER(14,2) DEFAULT 0,
    TOTAL_AMOUNT NUMBER(14,2) DEFAULT 0,
    RECEIVED_AMOUNT NUMBER(14,2) DEFAULT 0,
    BALANCE_AMOUNT NUMBER(14,2) DEFAULT 0,
    BDM1_ID NUMBER(10),
    BDM2_ID NUMBER(10),
    PAYMENT_TYPE VARCHAR2(50),
    SERVICE_ID NUMBER(10),
    SUB_SERVICE_ID NUMBER(10),
    REMARKS VARCHAR2(1000),
    PAYMENT_STATUS VARCHAR2(30) DEFAULT 'RECEIVED',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_BDE
FOREIGN KEY (BDE_USER_ID)
REFERENCES YUGEM_USERS(USER_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_CLIENT
FOREIGN KEY (CLIENT_ID)
REFERENCES YUGEM_CLIENTS(CLIENT_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_BDM1
FOREIGN KEY (BDM1_ID)
REFERENCES YUGEM_BDMS(BDM_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_BDM2
FOREIGN KEY (BDM2_ID)
REFERENCES YUGEM_BDMS(BDM_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_SERVICE
FOREIGN KEY (SERVICE_ID)
REFERENCES YUGEM_SERVICES(SERVICE_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT FK_PAYMENT_SUBSERVICE
FOREIGN KEY (SUB_SERVICE_ID)
REFERENCES YUGEM_SUB_SERVICES(SUB_SERVICE_ID);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT CK_PAYMENT_PERCENTAGE
CHECK (PAYMENT_PERCENTAGE IS NULL OR PAYMENT_PERCENTAGE >= 0);

ALTER TABLE YUGEM_PAYMENTS
ADD CONSTRAINT CK_PAYMENT_AMOUNTS
CHECK (
    BASIC_AMOUNT >= 0
    AND GST_AMOUNT >= 0
    AND TOTAL_AMOUNT >= 0
    AND RECEIVED_AMOUNT >= 0
    AND BALANCE_AMOUNT >= 0
);


CREATE TABLE YUGEM_PAYMENT_ATTACHMENTS (
    ATTACHMENT_ID NUMBER(12) PRIMARY KEY,
    PAYMENT_ID NUMBER(12) NOT NULL,
    FILE_TYPE VARCHAR2(30) NOT NULL,
    ORIGINAL_FILE_NAME VARCHAR2(255) NOT NULL,
    MIME_TYPE VARCHAR2(100),
    FILE_SIZE NUMBER(12),
    FILE_PATH VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE YUGEM_PAYMENT_ATTACHMENTS
ADD CONSTRAINT FK_ATTACHMENT_PAYMENT
FOREIGN KEY (PAYMENT_ID)
REFERENCES YUGEM_PAYMENTS(PAYMENT_ID)
ON DELETE CASCADE;


